import { UserSpecs } from '../types';

export interface CpuOption {
  id: string;
  name: string;
  brand: 'Intel' | 'AMD' | 'Apple' | 'Other';
  cores: number;
  threads: number;
  score: number; // Multi-thread PassMark / CPU-Mark
  singleScore: number;
  generation: string;
  architecture: 'Desktop' | 'Laptop';
}

export interface GpuOption {
  id: string;
  name: string;
  brand: 'Nvidia' | 'AMD' | 'Intel' | 'Apple' | 'Other';
  isIntegrated: boolean;
  vramGb: number;
  score: number; // 3DMark / PassMark G3D
  tier: number; // 0 to 5
}

import pcDatabase from './pc_database.json';

// STRICT RULE: Use pc_database.json as the ONLY data source.
// Never invent tiers or requirements.
export const CPU_DATABASE: CpuOption[] = (pcDatabase.cpus as any[]).map((c) => ({
  id: c.id,
  name: c.canonicalName || c.name,
  brand: (c.brand as any) || 'Other',
  cores: c.cores || 4,
  threads: c.threads || 8,
  score: c.score || 10000,
  singleScore: c.singleScore || 2500,
  generation: c.generation || c.notes || 'Modern Multi-Core',
  architecture: c.type === 'laptop' ? 'Laptop' : 'Desktop',
}));

export const GPU_DATABASE: GpuOption[] = (pcDatabase.gpus as any[]).map((g) => ({
  id: g.id,
  name: g.canonicalName || g.name,
  brand: (g.brand as any) || 'Other',
  isIntegrated: Boolean(g.isIntegrated),
  vramGb: g.vramGb || 4,
  score: g.score || 5000,
  tier: g.tier !== undefined ? Math.floor(g.tier / 2) : 2,
}));


